#!/usr/bin/env bash
set -u
umask 077

SECTION="monitors"
while [ $# -gt 0 ]; do
    case "$1" in
    --section) SECTION="${2:-}"; shift 2 ;;
    *) break ;;
    esac
done
case "$SECTION" in
'' | *[!a-z]*) echo "section must be lowercase a-z" >&2; exit 2 ;;
esac

cmd="${1:-}"
[ $# -gt 0 ] && shift

DIR="$HOME/.config/hypr/custom"
F="$DIR/macmono-generated.lua"
B="$F.bak"
LEGACY="$DIR/macmono-generated-input.lua"
RT="${XDG_RUNTIME_DIR:?XDG_RUNTIME_DIR is empty}/macmono"
P="$RT/generated.$SECTION.pending"
PREV="$RT/generated.$SECTION.prev"
PREVHAS="$RT/generated.$SECTION.had"

errs() { hyprctl configerrors 2>&1 | sed '/^[[:space:]]*$/d'; }
reload() { hyprctl reload >/dev/null 2>&1; sleep 0.7; }
rollback_all() {
    rm -f "$P"
    if [ -f "$B" ]; then mv -f "$B" "$F"; else rm -f "$F"; fi
    reload
}
rollback() {
    rm -f "$P"
    if [ ! -f "$PREV" ] || [ ! -f "$F" ]; then rollback_all; return; fi
    local had=0 tmp
    [ -f "$PREVHAS" ] && had=1
    tmp="$(mktemp "$RT/rb.XXXXXX")" || return 1
    awk -v n="$SECTION" -v prev="$PREV" -v had="$had" '
        $0 == "-- >>> macmono:" n {
            skipping = 1
            if (had) {
                print
                while ((getline line < prev) > 0) print line
                close(prev)
                print "-- <<< macmono:" n
            }
            next
        }
        $0 == "-- <<< macmono:" n { skipping = 0; next }
        skipping { next }
        { print }
    ' "$F" > "$tmp"
    cat "$tmp" > "$F"
    rm -f "$tmp"
    reload
}

begin() { printf -- '-- >>> macmono:%s\n' "$1"; }
end() { printf -- '-- <<< macmono:%s\n' "$1"; }

has_block() {
    [ -f "$2" ] && grep -qxF -- "-- >>> macmono:$1" "$2"
}
block() {
    [ -f "$2" ] || return 0
    awk -v n="$1" '
        $0 == "-- >>> macmono:" n { inblk = 1; next }
        $0 == "-- <<< macmono:" n { inblk = 0; next }
        inblk { print }
    ' "$2"
}

case "$cmd" in
apply)
    mkdir -p "$DIR" "$RT"
    body="$(mktemp "$RT/body.XXXXXX")" || exit 2
    cat > "$body"

    seed="$(mktemp "$RT/seed.XXXXXX")" || exit 2
    if [ -f "$F" ] && grep -q '^-- >>> macmono:' "$F"; then
        cp -f "$F" "$seed"
    else
        {
            if [ -f "$F" ]; then begin monitors; sed '/^-- Generated by macmono/d' "$F"; end monitors; fi
            if [ -f "$LEGACY" ]; then begin input; sed '/^-- Generated by macmono/d' "$LEGACY"; end input; fi
        } > "$seed"
    fi

    extras="$(grep -h '^-- >>> macmono:[a-z]*$' "$seed" 2>/dev/null | sed 's/^-- >>> macmono://' | grep -vxE 'monitors|input' | tr '\n' ' ')"
    names="monitors input $extras"
    case " $names " in
    *" $SECTION "*) ;;
    *) names="$names $SECTION" ;;
    esac

    out="$(mktemp "$RT/out.XXXXXX")" || exit 2
    {
        printf '%s\n' "-- Generated by macmono Settings. Do not edit by hand: it will be overwritten."
        printf '%s\n' "-- Single file for all macmono settings; each section is written separately."
        for n in $names; do
            if [ "$n" = "$SECTION" ]; then
                begin "$n"
                sed '/^-- Generated by macmono/d' "$body"
                end "$n"
            elif has_block "$n" "$seed"; then
                begin "$n"
                block "$n" "$seed"
                end "$n"
            fi
        done
    } > "$out"

    if [ ! -f "$P" ]; then
        rm -f "$PREV" "$PREVHAS"
        block "$SECTION" "$seed" > "$PREV"
        has_block "$SECTION" "$seed" && : > "$PREVHAS"
    fi

    before="$(errs)"
    if [ -f "$F" ]; then cp -f "$F" "$B"; else rm -f "$B"; fi
    cat "$out" > "$F"
    rm -f "$out" "$body" "$seed"

    reload
    after="$(errs)"
    if [ "$after" != "$before" ]; then
        printf '%s\n' "$after" >&2
        rollback_all
        exit 1
    fi

    rm -f "$LEGACY" "$LEGACY.bak"

    if [ -n "${1:-}" ]; then
        tok="$$-$(date +%s%N)"
        printf '%s' "$tok" > "$P"
        setsid -f bash "$0" --section "$SECTION" watchdog "$1" "$tok" >/dev/null 2>&1
    else
        rm -f "$P"
    fi
    ;;
watchdog)
    sleep "${1:-15}"
    [ -f "$P" ] && [ "$(cat "$P" 2>/dev/null)" = "${2:-}" ] && rollback
    ;;
confirm) rm -f "$P" ;;
restore) rollback ;;
*)
    echo "usage: $0 [--section name] apply [seconds] | confirm | restore" >&2
    exit 2
    ;;
esac
